#!/usr/bin/env python3
"""Append P3/P4 metrics for the 4P overlay theme.
Reads Logs/log.txt for 'Metric "Section::NameP3.." is missing' warnings, copies the matching P1 (for P3)
or P2 (for P4) value from Simply Love / _fallback metrics.ini and writes it to
Themes/Simply Love 4P/metrics-generated.ini sections (merged into metrics.ini between markers)."""
import re, sys, os, collections
repo = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
def load(path):
    d = collections.OrderedDict(); sec = None
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.rstrip("\n")
        m = re.match(r"\[(.+)\]", line)
        if m: sec = m.group(1); d.setdefault(sec, collections.OrderedDict()); continue
        m = re.match(r"([^=;#]+)=(.*)", line)
        if m and sec: d[sec][m.group(1)] = m.group(2)
    return d
base = [load(os.path.join(repo, "Themes", t, "metrics.ini")) for t in ("Simply Love", "_fallback")]
def lookup(sec, name):
    for d in base:
        if sec in d and name in d[sec]: return d[sec][name]
    return None
# Every metric whose key names player 1 or 2 ("...P1...", "...P2...") gets a P3 / P4 twin that
# copies the P1 / P2 value (so P3 behaves like P1 and P4 like P2 unless overridden in 4P metrics).
tok = re.compile(r"P([12])(?![a-z0-9])")
out = collections.OrderedDict()
unresolved = []
existing = {}
for d in base:
    for sec, kv in d.items():
        for k in kv: existing.setdefault(sec, set()).add(k)
for d in reversed(base):  # fallback first so Simply Love values win
    pass
seen = set()
for d in base:
    for sec, kv in d.items():
        for k, v in kv.items():
            m = tok.search(k)
            if not m: continue
            n = int(m.group(1)) + 2
            k2 = tok.sub("P%d" % n, k, count=1)
            if k2 in existing.get(sec, set()) or (sec, k2) in seen: continue
            seen.add((sec, k2))
            out.setdefault(sec, []).append((k2, v))
mpath = os.path.join(repo, "Themes", "Simply Love 4P", "metrics.ini")
txt = open(mpath).read().split("#### GENERATED")[0].rstrip() + "\n\n#### GENERATED by tools/gen-4p-metrics.py (do not edit below)\n"
for sec, items in out.items():
    txt += "[%s]\n" % sec + "".join("%s=%s\n" % kv for kv in items)
open(mpath, "w").write(txt)
print("generated", sum(len(v) for v in out.values()), "metrics; unresolved:", unresolved[:10], len(unresolved))
